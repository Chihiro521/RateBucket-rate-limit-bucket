import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);

async function readBody(filename) {
  const markdown = (await readFile(new URL(filename, root), "utf8")).replace(/\r\n/g, "\n");
  const lines = markdown.trim().split("\n");
  if (lines[0] !== "# RateBucket" || lines[1] !== "" || lines[3] !== "") {
    throw new Error(`Unexpected README header in ${filename}`);
  }
  return lines.slice(4).join("\n");
}

const english = await readBody("README.en.md");
const chinese = await readBody("README.zh-CN.md");
const markdown = `<!-- Generated by scripts/build-readme.mjs from the two language source files. -->

# RateBucket

<details name="readme-language" open>
<summary>English</summary>

<a id="readme-en"></a>

**English** | [中文](#user-content-readme-zh)

${english}

</details>

<details name="readme-language">
<summary>中文</summary>

<a id="readme-zh"></a>

[English](#user-content-readme-en) | **中文**

${chinese}

</details>
`;

await writeFile(new URL("README.md", root), markdown, "utf8");
